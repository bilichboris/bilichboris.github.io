def matmul(A, B):
    if not A or not B or not all(isinstance(row, list) and row for row in A + B):
        raise AssertionError("empty or malformed matrix")
    if any(len(row) != len(A[0]) for row in A):
        raise AssertionError("ragged matrix")
    if any(len(row) != len(B[0]) for row in B):
        raise AssertionError("ragged matrix")
    if len(A[0]) != len(B):
        raise AssertionError("incompatible matrix dimensions")

    C = [[0] * len(B[0]) for _ in range(len(A))]
    for i in range(len(A)):
        for k in range(len(B)):
            for j in range(len(B[0])):
                C[i][j] += A[i][k] * B[k][j]
    return C


def check_nonnegative_integer_entries(M):
    for row in M:
        for x in row:
            if isinstance(x, bool) or not isinstance(x, int) or x < 0:
                raise AssertionError(f"invalid matrix entry: {x!r}")


def main():
    if not PAIRS:
        raise AssertionError("empty certificate")

    for R, S in PAIRS:
        check_nonnegative_integer_entries(R)
        check_nonnegative_integer_entries(S)

    if matmul(PAIRS[0][0], PAIRS[0][1]) != [[2]]:
        raise AssertionError("certificate does not start at [[2]]")

    for i in range(len(PAIRS) - 1):
        R, S = PAIRS[i]
        R1, S1 = PAIRS[i + 1]
        if matmul(S, R) != matmul(R1, S1):
            raise AssertionError(f"chain breaks between pairs {i} and {i + 1}")

    if matmul(PAIRS[-1][1], PAIRS[-1][0]) != ASHLEY:
        raise AssertionError("certificate does not end at the Ashley matrix")

    print(f"OK: {len(PAIRS)} pairs verified.")


if __name__ == "__main__":
    main()
